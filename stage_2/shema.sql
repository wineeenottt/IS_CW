BEGIN;

CREATE TABLE users (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	email VARCHAR(255) NOT NULL UNIQUE,
	password_hash VARCHAR(255) NOT NULL,
	email_verified BOOLEAN NOT NULL DEFAULT FALSE,
	telegram_id BIGINT UNIQUE,
	role VARCHAR(20) NOT NULL DEFAULT 'USER'
    	CHECK (role IN ('USER', 'MODERATOR', 'ADMIN')),
	status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
    	CHECK (status IN ('ACTIVE', 'BLOCKED', 'DELETED')),
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	deleted_at TIMESTAMPTZ,
	CHECK ((status = 'DELETED') = (deleted_at IS NOT NULL))
);

CREATE TABLE auth_token (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	type VARCHAR(30) NOT NULL
    	CHECK (type IN ('EMAIL_VERIFY', 'PASSWORD_RESET', 'TELEGRAM_LINK')),
	token_hash VARCHAR(64) NOT NULL UNIQUE,
	expires_at TIMESTAMPTZ NOT NULL,
	used_at TIMESTAMPTZ
);

CREATE TABLE profile (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
	name VARCHAR(100) NOT NULL CHECK (length(btrim(name)) > 0),
	birth_date DATE NOT NULL,
	gender VARCHAR(20) NOT NULL CHECK (gender IN ('MALE', 'FEMALE')),
	looking_for VARCHAR(20) NOT NULL CHECK (looking_for IN ('MALE', 'FEMALE', 'ANY')),
	city VARCHAR(100) NOT NULL CHECK (length(btrim(city)) > 0),
	description TEXT,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE location (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	profile_id BIGINT NOT NULL UNIQUE REFERENCES profile(id) ON DELETE CASCADE,
	latitude NUMERIC(9, 6) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
	longitude NUMERIC(9, 6) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
	updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE photo (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	profile_id BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
	url VARCHAR(500) NOT NULL,
	is_main BOOLEAN NOT NULL DEFAULT FALSE,
	sort_order INT NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
	moderation_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
    	CHECK (moderation_status IN ('PENDING', 'APPROVED', 'HIDDEN')),
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	UNIQUE (profile_id, sort_order) DEFERRABLE INITIALLY DEFERRED
);

CREATE UNIQUE INDEX uq_photo_main ON photo (profile_id) WHERE is_main;

CREATE TABLE interest (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE profile_interest (
	profile_id BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
	interest_id BIGINT NOT NULL REFERENCES interest(id) ON DELETE RESTRICT,
	PRIMARY KEY (profile_id, interest_id)
);

CREATE TABLE reaction (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	from_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	to_profile_id BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
	type VARCHAR(10) NOT NULL CHECK (type IN ('LIKE', 'DISLIKE')),
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	UNIQUE (from_user_id, to_profile_id)
);

CREATE TABLE match (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	user1_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	user2_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	CHECK (user1_id < user2_id),
	UNIQUE (user1_id, user2_id)
);

CREATE TABLE dialog (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	match_id BIGINT NOT NULL UNIQUE REFERENCES match(id) ON DELETE CASCADE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	last_message_at TIMESTAMPTZ
);

CREATE TABLE message (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	dialog_id BIGINT NOT NULL REFERENCES dialog(id) ON DELETE CASCADE,
	sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
	text TEXT NOT NULL CHECK (length(btrim(text)) > 0),
	status VARCHAR(10) NOT NULL DEFAULT 'SENT'
    	CHECK (status IN ('SENT', 'READ', 'HIDDEN')),
	created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE block (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	CHECK (blocker_id <> blocked_id),
	UNIQUE (blocker_id, blocked_id)
);

CREATE TABLE profile_view (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	viewer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	profile_id BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE complaint_reason (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	name VARCHAR(100) NOT NULL UNIQUE,
	description TEXT
);

CREATE TABLE complaint (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	reporter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
	target_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
	moderator_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	profile_id BIGINT REFERENCES profile(id) ON DELETE SET NULL,
	message_id BIGINT REFERENCES message(id) ON DELETE SET NULL,
	reason_id BIGINT NOT NULL REFERENCES complaint_reason(id) ON DELETE RESTRICT,
	comment TEXT,
	status VARCHAR(20) NOT NULL DEFAULT 'NEW'
    	CHECK (status IN ('NEW', 'IN_REVIEW', 'NEED_INFO', 'REJECTED', 'ACCEPTED')),
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	resolved_at TIMESTAMPTZ,
	CHECK (reporter_id <> target_user_id),
	CHECK ((status IN ('REJECTED', 'ACCEPTED')) = (resolved_at IS NOT NULL))
);

CREATE TABLE restriction (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	type VARCHAR(30) NOT NULL CHECK (type IN ('BAN', 'NO_MESSAGES', 'HIDE_PROFILE')),
	reason TEXT NOT NULL,
	complaint_id BIGINT REFERENCES complaint(id) ON DELETE SET NULL,
	created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	expires_at TIMESTAMPTZ CHECK (expires_at IS NULL OR expires_at > created_at),
	CHECK (created_by <> user_id)
);

CREATE TABLE notification (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
	type VARCHAR(30) NOT NULL
    	CHECK (type IN ('MATCH', 'MESSAGE', 'RESTRICTION', 'SYSTEM')),
	title VARCHAR(150) NOT NULL,
	text TEXT NOT NULL,
	is_read BOOLEAN NOT NULL DEFAULT FALSE,
	telegram_status VARCHAR(20) CHECK (telegram_status IN ('PENDING', 'SENT', 'FAILED')),
	telegram_attempts INT NOT NULL DEFAULT 0 CHECK (telegram_attempts >= 0),
	created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE journal (
	id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
	user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
	action VARCHAR(50) NOT NULL,
	entity_type VARCHAR(30),
	entity_id BIGINT,
	details JSONB,
	created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
	CHECK ((entity_type IS NULL) = (entity_id IS NULL))
);

COMMIT;
